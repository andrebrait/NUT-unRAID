const NUT_MC_UNSAFE = '/[\x00-\x1f\x7f"\\\\$`]/';
const NUT_MC_ID = '/^[A-Za-z0-9_.-]{1,64}$/';

function nut_mc_read_cfg($path) {
    $cfg = is_file($path) ? parse_ini_file($path, false, INI_SCANNER_RAW) : [];
    return is_array($cfg) ? $cfg : [];
}

function nut_mc_settings(array $cfg) {
    return array_merge(nut_mc_read_cfg(__DIR__ . '/../default.cfg'), $cfg);
}

function nut_mc_put($path, $text) {
    $tmp = "$path.tmp";
    if (file_put_contents($tmp, $text) !== strlen($text) || !rename($tmp, $path)) {
        @unlink($tmp);
        return false;
    }
    return true;
}

function nut_mc_write_cfg($path, array $cfg) {
    $text = '';
    foreach ($cfg as $key => $value) {
        $text .= "$key=\"$value\"\n";
    }
    return nut_mc_put($path, $text);
}

/* Secrets and multi-line fields are stored base64-encoded; legacy values were made with `echo | base64`. */
function nut_mc_decode($value) {
    $text = base64_decode((string)$value, true);
    return $text === false ? null : rtrim($text, "\n");
}

function nut_mc_custom(array $cfg, $key) {
    $lines = array_map('rtrim', explode("\n", str_replace("\r", '', nut_mc_decode($cfg[$key] ?? '') ?? '')));
    while ($lines && end($lines) === '') {
        array_pop($lines);
    }
    return $lines ? implode("\n", $lines) . "\n" : '';
}

/* Quote a value for NUT's config parser: inside quotes, \ " and # must be escaped. */
function nut_mc_quote($value) {
    return '"' . strtr((string)$value, ['\\' => '\\\\', '"' => '\\"', '#' => '\\#']) . '"';
}

/* Split one line into words the way NUT's parseconf does; $error is set for lines NUT would reject.
 * The states follow common/parseconf.c by Russell Kroll and the NUT developers:
 * https://github.com/networkupstools/nut/blob/v2.8.4/common/parseconf.c */
function nut_mc_words($line, &$error = null) {
    $error = null;
    $words = [];
    $word = null;
    $state = 'start';
    for ($i = 0, $len = strlen($line); $i < $len; $i++) {
        $ch = $line[$i];
        switch ($state) {
            case 'start':
                if ($ch === '#') break 2;
                if (ctype_space($ch)) break;
                if ($ch === '=') { $words[] = '='; break; }
                $word = '';
                if ($ch === '"') { $state = 'quote'; break; }
                if ($ch === '\\') { $state = 'literal'; break; }
                $word = $ch;
                $state = 'word';
                break;
            case 'word':
                if ($ch === '#') { $words[] = $word; $word = null; break 2; }
                if (ctype_space($ch) || $ch === '=') {
                    $words[] = $word;
                    if ($ch === '=') $words[] = '=';
                    $word = null;
                    $state = 'start';
                    break;
                }
                if ($ch === '\\') { $state = 'literal'; break; }
                $word .= $ch;
                break;
            case 'literal':
                $word .= $ch;
                $state = 'word';
                break;
            case 'quote':
                if ($ch === '#') { $error = 'unescaped # inside quotes'; return null; }
                if ($ch === '"') { $words[] = $word; $word = null; $state = 'start'; break; }
                if ($ch === '\\') { $state = 'quoteliteral'; break; }
                $word .= $ch;
                break;
            case 'quoteliteral':
                $word .= $ch;
                $state = 'quote';
                break;
        }
    }
    if ($state === 'quote' || $state === 'quoteliteral') { $error = 'unterminated quote'; return null; }
    if ($state === 'literal') { $error = 'line ends with a backslash'; return null; }
    if ($word !== null) $words[] = $word;
    return $words;
}

/* Directive entries of a config text (blank lines and comments skipped). */
function nut_mc_parse($text) {
    $entries = [];
    $section = null;
    foreach (explode("\n", str_replace("\r", '', (string)$text)) as $i => $raw) {
        $words = nut_mc_words($raw, $error);
        if ($error === null && !$words) continue;
        $header = $words && count($words) === 1 && preg_match('/^\[(.*)\]$/', $words[0], $m);
        if ($header) $section = $m[1];
        $entries[] = ['line' => $i + 1, 'raw' => trim($raw), 'words' => $words ?? [], 'error' => $error,
            'section' => $section, 'header' => (bool)$header];
    }
    return $entries;
}

/* Identity of a directive for override detection; repeatable upsmon directives are keyed by their target. */
function nut_mc_key($file, array $words) {
    $key = strtolower($words[0] ?? '');
    if ($file === 'upsmon.conf' && in_array($key, ['monitor', 'notifyflag', 'notifymsg'], true)) {
        $key .= ' ' . strtolower($words[1] ?? '');
    }
    return $key;
}

function nut_mc_generate(array $c, $withCustom = true) {
    $block = function ($key, $title = 'Custom directives') use ($c, $withCustom) {
        $text = $withCustom ? nut_mc_custom($c, $key) : '';
        return $text === '' ? '' : "# $title\n$text";
    };
    $slave = $c['MODE'] === 'slave';
    $files = array_fill_keys(NUT_MC_FILES, NUT_MC_HEADER);

    $files['nut.conf'] .= 'MODE=' . ($slave ? 'netclient' : $c['MODE']) . "\n" . $block('CUSTOM_NUT');

    if (!$slave) {
        $global = $block('CUSTOM_UPSGLOBAL', 'Custom global directives');
        $ups = ($global === '' ? '' : "$global\n") . "[{$c['NAME']}]\n";
        $ups .= "\tdriver = " . ($c['DRIVER'] === 'custom' ? $c['SERIAL'] : $c['DRIVER']) . "\n";
        $ups .= "\tport = " . nut_mc_quote($c['PORT']) . "\n";
        if ($c['DRIVER'] === 'snmp-ups') {
            $ups .= "\tpollfreq = {$c['POLL']}\n\tcommunity = " . nut_mc_quote($c['COMMUNITY']) . "\n";
            $ups .= "\tsnmp_version = {$c['SNMPVER']}\n";
            if ($c['SNMPMIB'] !== 'auto') $ups .= "\tmibs = {$c['SNMPMIB']}\n";
        }
        if ($c['DEBLEVEL'] !== 'default') $ups .= "\tdebug_min = {$c['DEBLEVEL']}\n";
        $files['ups.conf'] .= $ups . $block('CUSTOM_UPS');

        $listen = $c['MODE'] === 'netserver' ? preg_split('/\s+/', trim($c['LISTEN'])) : ['127.0.0.1'];
        foreach ($listen as $address) {
            $files['upsd.conf'] .= "LISTEN $address\n";
        }
        $files['upsd.conf'] .= $block('CUSTOM_UPSD');

        // master/slave instead of primary/secondary: the legacy 2.7.4 backend only knows these
        $users = [[$c['MONUSER'], 'MONPASS', ['upsmon master']]];
        if ($c['MODE'] === 'netserver') $users[] = [$c['SLAVEUSER'], 'SLAVEPASS', ['upsmon slave']];
        if ($c['ADMINUSER'] !== '') $users[] = [$c['ADMINUSER'], 'ADMINPASS', ['actions = SET', 'actions = FSD', 'instcmds = ALL']];
        foreach ($users as [$user, $pass, $lines]) {
            $files['upsd.users'] .= "[$user]\n\tpassword = " . nut_mc_quote(nut_mc_decode($c[$pass])) . "\n";
            foreach ($lines as $line) {
                $files['upsd.users'] .= "\t$line\n";
            }
        }
        $files['upsd.users'] .= $block('CUSTOM_USERS');
    }

    $files['upsmon.conf'] .= "MONITOR {$c['NAME']}@{$c['IPADDR']} 1 {$c['MONUSER']} "
        . nut_mc_quote(nut_mc_decode($c['MONPASS'])) . ($slave ? ' slave' : ' master') . "\n"
        . "SHUTDOWNCMD \"/sbin/poweroff\"\n"
        . 'POWERDOWNFLAG "/etc/nut/' . ($c['UPSKILL'] === 'enable' ? 'killpower' : 'no_killpower') . "\"\n"
        . "NOTIFYCMD \"/usr/sbin/nut-notify\"\n"
        . "NOTIFYFLAG ONBATT SYSLOG+EXEC\nNOTIFYFLAG ONLINE SYSLOG+EXEC\nNOTIFYFLAG REPLBATT SYSLOG+EXEC\n"
        . ($c['DEBLEVELMON'] !== 'default' ? "DEBUG_MIN {$c['DEBLEVELMON']}\n" : '')
        . $block('CUSTOM_UPSMON');

    $files['upssched.conf'] .= $block('CUSTOM_UPSSCHED');
    return $files;
}

function nut_mc_unsafe(array $values) {
    $errors = [];
    foreach ($values as $key => $value) {
        if (!is_string($value) || preg_match(NUT_MC_UNSAFE, $value)) {
            $errors[] = "Setting $key: quotes, backslashes, \$, backticks and line breaks are not allowed.";
        }
    }
    return $errors;
}

function nut_mc_password_error($label, $value) {
    $pass = nut_mc_decode($value);
    if ($pass === null || $pass === '') return "$label Password: must not be empty.";
    // upsmon and upscmd send the password unquoted over the network protocol
    if (!preg_match('/^[\x21-\x7e]+$/', $pass) || strpbrk($pass, '#"\\=') !== false) {
        return "$label Password: use printable ASCII characters without spaces or # \" \\ = (NUT sends passwords unquoted over the network).";
    }
    return null;
}

function nut_mc_validate(array $c) {
    $errors = nut_mc_unsafe($c);
    if ($errors) return $errors;
    if (!in_array($c['MODE'], ['standalone', 'netserver', 'slave'], true)) return ['NUT Mode: unknown mode.'];
    $slave = $c['MODE'] === 'slave';
    $netserver = $c['MODE'] === 'netserver';

    if (!preg_match(NUT_MC_ID, $c['NAME'])) $errors[] = 'UPS Name: use 1-64 letters, digits, "_", "." or "-".';
    if ($slave && !preg_match('/^([A-Za-z0-9.-]+|\[[0-9A-Fa-f:.]+\])(:[0-9]{1,5})?$/', $c['IPADDR'])) {
        $errors[] = 'NUT Master IP Address: enter an IP address or hostname, optionally followed by :port.';
    }
    if (!$slave && $c['IPADDR'] !== '127.0.0.1') $errors[] = 'NUT Master IP Address: must be 127.0.0.1 unless in slave mode.';

    $users = [['MONUSER', 'MONPASS', 'NUT Monitor']];
    if ($netserver) $users[] = ['SLAVEUSER', 'SLAVEPASS', 'NUT Slave'];
    if ($c['ADMINUSER'] !== '' || (string)nut_mc_decode($c['ADMINPASS']) !== '') $users[] = ['ADMINUSER', 'ADMINPASS', 'NUT Admin'];
    $names = [];
    foreach ($users as [$user, $pass, $label]) {
        if (!preg_match(NUT_MC_ID, $c[$user])) $errors[] = "$label Username: use 1-64 letters, digits, \"_\", \".\" or \"-\".";
        elseif (isset($names[$c[$user]])) $errors[] = "$label Username: must differ from the other NUT usernames.";
        $names[$c[$user]] = true;
        if ($error = nut_mc_password_error($label, $c[$pass])) $errors[] = $error;
    }

    if ($netserver) {
        $listen = preg_split('/\s+/', trim($c['LISTEN']));
        if (array_filter($listen, fn($a) => !preg_match('/^[A-Za-z0-9.:-]+$/', $a))) {
            $errors[] = 'NUT Listen Addresses: enter IP addresses or hostnames separated by spaces.';
        } elseif (!array_intersect($listen, ['0.0.0.0', '127.0.0.1'])) {
            $errors[] = 'NUT Listen Addresses: include 0.0.0.0 or 127.0.0.1, the local NUT monitor connects to 127.0.0.1.';
        }
    }

    if (!$slave) {
        if ($c['DRIVER'] === 'custom') {
            if (!preg_match('/^[A-Za-z0-9_-]{1,64}$/', $c['SERIAL'])) $errors[] = 'UPS Driver: enter a valid custom driver name.';
        } elseif (!in_array($c['DRIVER'], NUT_MC_DRIVERS, true)) {
            $errors[] = 'UPS Driver: unknown driver.';
        }
        if (!preg_match('/^[\x21-\x7e]+$/', $c['PORT'])) $errors[] = 'UPS Driver Port: must not be empty or contain spaces.';
        if (!preg_match('/^(default|[1-6])$/', $c['DEBLEVEL'])) $errors[] = 'UPS Driver Debug Level: invalid value.';
        if ($c['DRIVER'] === 'snmp-ups') {
            if (!preg_match('/^[1-9][0-9]{0,4}$/', $c['POLL'])) $errors[] = 'SNMP Polling Frequency: enter a number of seconds.';
            if (!preg_match('/^[\x20-\x7e]+$/', $c['COMMUNITY'])) $errors[] = 'SNMP Community: must not be empty.';
            if (!in_array($c['SNMPVER'], ['v1', 'v2c', 'v3'], true)) $errors[] = 'SNMP Version: invalid value.';
            if ($c['SNMPMIB'] !== 'auto' && !in_array($c['SNMPMIB'], NUT_MC_MIBS, true)) $errors[] = 'SNMP Definition MIB: invalid value.';
        }
    }
    if (!preg_match('/^(default|[1-6])$/', $c['DEBLEVELMON'])) $errors[] = 'NUT Monitor Debug Level: invalid value.';
    if (!in_array($c['UPSKILL'], ['enable', 'disable'], true)) $errors[] = 'Disable UPS Power after Shutdown: invalid value.';
    if ($errors) return $errors;

    $base = nut_mc_generate($c, false);
    $generatedUsers = array_column(array_filter(nut_mc_parse($base['upsd.users']), fn($d) => $d['header']), 'section');
    foreach (NUT_MC_CUSTOM as $key => [$file, $label]) {
        if ($slave && in_array($key, NUT_MC_SLAVE_UNUSED, true)) continue;
        if (nut_mc_decode($c[$key] ?? '') === null) {
            $errors[] = "Custom $label directives: the stored value is corrupt, clear the field and save again.";
            continue;
        }
        $managed = [];
        foreach (nut_mc_parse($base[$file]) as $d) {
            if (!$d['header'] && ($key !== 'CUSTOM_UPSGLOBAL' || $d['section'] === null)) $managed[nut_mc_key($file, $d['words'])] = true;
        }
        foreach (nut_mc_parse(nut_mc_custom($c, $key)) as $d) {
            $where = "Custom $label directives, line {$d['line']}";
            if (preg_match('/[^\x20-\x7e\t]/', $d['raw'])) {
                $errors[] = "$where: only printable ASCII characters are supported by NUT.";
            } elseif ($d['error']) {
                $errors[] = "$where: {$d['error']}.";
            } elseif ($d['header'] && $file === 'ups.conf') {
                $errors[] = "$where: only one UPS is supported, remove the section [{$d['section']}].";
            } elseif ($d['header'] && $file === 'upsd.users' && in_array($d['section'], $generatedUsers, true)) {
                $errors[] = "$where: user [{$d['section']}] is generated from the settings above and cannot be redefined here.";
            } elseif (!$d['header'] && $file === 'upsd.users' && $d['section'] === null) {
                $errors[] = "$where: start with a [username] section, otherwise the directive is added to a generated user.";
            } elseif (!$d['header'] && $file !== 'upsd.users' && isset($managed[nut_mc_key($file, $d['words'])])) {
                $errors[] = "$where: \"{$d['words'][0]}\" is set from the settings above and cannot be overridden here.";
            }
        }
    }
    return $errors;
}

/* Map one ups.conf directive of the UPS section to settings; false leaves it for the custom field. */
function nut_mc_ups_directive(array $d, array &$set, array &$taken, $snmp) {
    $w = $d['words'];
    if ($d['error'] || count($w) !== 3 || $w[1] !== '=') return false;
    $key = strtolower($w[0]);
    $value = $w[2];
    if (isset($taken[$key])) return false;
    switch ($key) {
        case 'driver':
            if (in_array($value, NUT_MC_DRIVERS, true)) {
                $set['DRIVER'] = $value;
            } else {
                $set['DRIVER'] = 'custom';
                $set['SERIAL'] = $value;
            }
            break;
        case 'port':
            $set['PORT'] = $value;
            break;
        case 'debug_min':
            if (!preg_match('/^[1-6]$/', $value)) return false;
            $set['DEBLEVEL'] = $value;
            break;
        case 'pollfreq':
            if (!$snmp || !preg_match('/^[1-9][0-9]{0,4}$/', $value)) return false;
            $set['POLL'] = $value;
            break;
        case 'community':
            if (!$snmp) return false;
            $set['COMMUNITY'] = $value;
            break;
        case 'snmp_version':
            if (!$snmp || !in_array($value, ['v1', 'v2c', 'v3'], true)) return false;
            $set['SNMPVER'] = $value;
            break;
        case 'mibs':
            if (!$snmp || !in_array($value, NUT_MC_MIBS, true)) return false;
            $set['SNMPMIB'] = $value;
            break;
        default:
            return false;
    }
    $taken[$key] = true;
    return true;
}

function nut_mc_section_driver(array $entries, $section) {
    foreach ($entries as $d) {
        if ($d['section'] === $section && !$d['header'] && count($d['words']) === 3 && strtolower($d['words'][0]) === 'driver') return $d['words'][2];
    }
    return null;
}

function nut_mc_upsmon_directive(array $d, array &$set, array &$taken) {
    $w = $d['words'];
    if ($d['error']) return false;
    $key = nut_mc_key('upsmon.conf', $w);
    $count = count($w);
    if (isset($taken[$key])) return false;
    switch ($key) {
        case 'shutdowncmd':
            if ($count !== 2 || $w[1] !== '/sbin/poweroff') return false;
            break;
        case 'notifycmd':
            if ($count !== 2 || $w[1] !== '/usr/sbin/nut-notify') return false;
            break;
        case 'powerdownflag':
            if ($count !== 2 || !in_array($w[1], ['/etc/nut/killpower', '/etc/nut/no_killpower'], true)) return false;
            $set['UPSKILL'] = $w[1] === '/etc/nut/killpower' ? 'enable' : 'disable';
            break;
        case 'notifyflag onbatt':
        case 'notifyflag online':
        case 'notifyflag replbatt':
            if ($count !== 3 || strtoupper($w[2]) !== 'SYSLOG+EXEC') return false;
            break;
        case 'debug_min':
            if ($count !== 2 || !preg_match('/^[1-6]$/', $w[1])) return false;
            $set['DEBLEVELMON'] = $w[1];
            break;
        default:
            return false;
    }
    $taken[$key] = true;
    return true;
}

/*
 * Import a previous configuration: $cfg is the old nut3.cfg, $files the old NUT files (name => text|null).
 * Returns [settings, notes]. Recognised directives become settings, everything else lands in the
 * custom fields, where nut_mc_validate() reports conflicts until the user resolves them.
 */
function nut_mc_import(array $cfg, array $files) {
    $manual = $cfg['MANUAL'] ?? 'disable';
    unset($cfg['MANUAL']);
    $c = nut_mc_settings($cfg);
    $notes = [];
    $custom = array_fill_keys(array_keys(NUT_MC_CUSTOM), []);
    $parse = fn($name) => nut_mc_parse($files[$name] ?? '');

    if (!in_array($c['MODE'], ['standalone', 'netserver', 'slave'], true)) {
        $notes[] = 'The NUT mode setting was invalid and was reset to standalone.';
        $c['MODE'] = 'standalone';
    }
    $mode = $c['MODE'];
    $slave = $mode === 'slave';

    // Legacy write_config rewrote the GUI-managed lines from the settings at every start, so the
    // settings are authoritative for them unless manual mode left that file alone.
    $fromFile = ['ups' => in_array($manual, ['enable', 'onlyups'], true), 'mon' => $manual === 'enable', 'file' => true];
    $values = [];
    $set = function ($group, array $found) use (&$c, &$notes, &$values, $fromFile) {
        foreach ($found as $key => $value) {
            $values[$key] = $value;
            if (!$fromFile[$group] || ($c[$key] ?? null) === $value) continue;
            if (preg_match(NUT_MC_UNSAFE, $value)) {
                $notes[] = "The value for $key contains unsupported characters and was not imported; check that setting.";
            } else {
                $c[$key] = $value;
            }
        }
    };
    if ($manual === 'enable' || $manual === 'onlyups') {
        $notes[] = 'Manual configuration mode was enabled. Your configuration files were imported into the settings and custom directive fields; check them carefully.';
    }

    if (!$slave) {
        $entries = $parse('ups.conf');
        $sections = array_values(array_unique(array_column(array_filter($entries, fn($d) => $d['header']), 'section')));
        $pick = in_array($c['NAME'], $sections, true) ? $c['NAME'] : ($sections[0] ?? null);
        if ($pick === null) {
            $notes[] = 'ups.conf: no UPS section was found, the UPS driver settings were kept as they were.';
        } else {
            $found = ['NAME' => $pick];
            $taken = [];
            $snmp = nut_mc_section_driver($entries, $pick) === 'snmp-ups';
            foreach ($entries as $d) {
                if ($d['section'] === null) {
                    $custom['CUSTOM_UPSGLOBAL'][] = $d['raw'];
                } elseif ($d['section'] !== $pick || (!$d['header'] && !nut_mc_ups_directive($d, $found, $taken, $snmp))) {
                    $custom['CUSTOM_UPS'][] = $d['raw'];
                }
            }
            $set('ups', $found);
            if (count($sections) > 1) {
                $notes[] = 'ups.conf: more than one UPS section was found, but only one UPS is supported. The other sections were moved to the custom directives and must be removed there.';
            }
        }
    }

    $entries = $parse('upsmon.conf');
    $monitor = null;
    foreach ($entries as $d) {
        if ($d['error'] || count($d['words']) !== 6 || strtoupper($d['words'][0]) !== 'MONITOR') continue;
        $monitor = $monitor ?? $d;
        if (explode('@', $d['words'][1])[0] === $c['NAME']) {
            $monitor = $d;
            break;
        }
    }
    if ($monitor === null) {
        $notes[] = 'upsmon.conf: no MONITOR line was found, the monitor is now generated from the settings.';
    } else {
        [, $system, $power, $user, $pass, $type] = $monitor['words'];
        [$name, $host] = array_pad(explode('@', $system, 2), 2, '');
        $found = ['IPADDR' => $host, 'MONUSER' => $user, 'MONPASS' => base64_encode($pass)];
        if ($slave) $found['NAME'] = $name;
        $set('mon', $found);
        if (!$slave && $name !== $c['NAME']) {
            $notes[] = "upsmon.conf: the MONITOR line watched UPS \"$name\", the generated configuration monitors the configured UPS \"{$c['NAME']}\".";
        }
        if ($power !== '1') $notes[] = 'upsmon.conf: the MONITOR power value is now always 1.';
        if (in_array(strtolower($type), ['master', 'primary'], true) === $slave) {
            $notes[] = 'upsmon.conf: the MONITOR role did not match the NUT mode, it now follows the mode (' . ($slave ? 'slave' : 'master') . ').';
        }
    }
    $found = [];
    $taken = [];
    foreach ($entries as $d) {
        if ($d !== $monitor && !nut_mc_upsmon_directive($d, $found, $taken)) $custom['CUSTOM_UPSMON'][] = $d['raw'];
    }
    $set('mon', $found);

    if ($slave) {
        $notes[] = 'Slave mode runs no local UPS driver or upsd, so ups.conf, upsd.conf and upsd.users were not imported.';
    } else {
        $listen = [];
        foreach ($parse('upsd.conf') as $d) {
            $w = $d['words'];
            if (!$d['error'] && strtoupper($w[0] ?? '') === 'LISTEN' && preg_match('/^[A-Za-z0-9.:-]+$/', $w[1] ?? '')
                && (count($w) === 2 || (count($w) === 3 && $w[2] === '3493'))) {
                $listen[] = $w[1];
            } else {
                $custom['CUSTOM_UPSD'][] = $d['raw'];
            }
        }
        if ($listen) $set('file', ['LISTEN' => implode(' ', array_unique($listen))]);

        $sections = [];
        foreach ($parse('upsd.users') as $d) {
            if ($d['section'] === null) {
                $custom['CUSTOM_USERS'][] = $d['raw'];
            } elseif ($d['header']) {
                $sections[$d['section']] = $sections[$d['section']] ?? [];
            } else {
                $sections[$d['section']][] = $d;
            }
        }
        $haveSlave = $haveAdmin = $haveMon = false;
        foreach ($sections as $user => $entries) {
            $pass = $type = null;
            $rest = [];
            $adminOnly = true;
            foreach ($entries as $d) {
                $w = $d['words'];
                $key = strtolower($w[0] ?? '');
                if (!$d['error'] && $pass === null && $key === 'password' && count($w) === 3 && $w[1] === '=') {
                    $pass = $w[2];
                    continue;
                }
                if (!$d['error'] && $type === null && $key === 'upsmon' && count($w) === 2) {
                    $type = strtolower($w[1]);
                    continue;
                }
                $adminOnly = $adminOnly && !$d['error'] && count($w) === 3 && $w[1] === '='
                    && in_array("$key=" . strtolower($w[2]), ['actions=set', 'actions=fsd', 'instcmds=all'], true);
                $rest[] = $d;
            }
            $raw = array_merge(["[$user]"], array_column($rest, 'raw'));
            if (!$haveMon && $user === $c['MONUSER'] && in_array($type, ['master', 'primary'], true)) {
                $haveMon = true;
                if ($pass !== nut_mc_decode($c['MONPASS'])) {
                    $notes[] = "upsd.users: the password of user \"$user\" differed from the one upsmon.conf uses, the upsmon.conf password is now used for both.";
                }
            } elseif (!$haveSlave && in_array($type, ['slave', 'secondary'], true)) {
                $haveSlave = true;
                $set('mon', ['SLAVEUSER' => $user, 'SLAVEPASS' => base64_encode((string)$pass)]);
            } elseif ($type === null && $pass !== null && $rest && $adminOnly) {
                if ($user === 'admin' && $pass === 'adminpass') {
                    $notes[] = 'upsd.users: the default admin user (admin/adminpass) was removed. Set the NUT Admin Username and Password to use NUT Commands.';
                    continue;
                }
                if ($haveAdmin) {
                    $custom['CUSTOM_USERS'] = array_merge($custom['CUSTOM_USERS'], $raw);
                    continue;
                }
                $haveAdmin = true;
                $set('file', ['ADMINUSER' => $user, 'ADMINPASS' => base64_encode($pass)]);
                $notes[] = "upsd.users: user \"$user\" was imported as the NUT Admin user used by NUT Commands.";
                continue;
            } else {
                $rest = $entries;
                $raw = array_merge(["[$user]"], array_column($rest, 'raw'));
            }
            if ($rest) $custom['CUSTOM_USERS'] = array_merge($custom['CUSTOM_USERS'], $raw);
        }
        if (!$haveMon) $notes[] = "upsd.users: user \"{$c['MONUSER']}\" used by upsmon was not found, it is now generated.";
        if ($mode === 'standalone' && ($haveSlave || array_diff(explode(' ', $values['LISTEN'] ?? '127.0.0.1'), ['127.0.0.1']))) {
            $notes[] = 'Standalone mode now keeps upsd local: it only listens on 127.0.0.1 and the slave user is not generated. Choose Netserver mode if other machines connect to this server.';
        }
    }

    foreach ($parse('nut.conf') as $d) {
        $w = $d['words'];
        if (!isset($nutMode) && !$d['error'] && strtoupper($w[0] ?? '') === 'MODE' && count($w) === 3 && $w[1] === '=') {
            $nutMode = $w[2] === 'netclient' ? 'slave' : $w[2];
            if ($nutMode !== $mode) $notes[] = "nut.conf: MODE $w[2] was ignored, the plugin's NUT mode setting ($mode) was in effect and is kept.";
            continue;
        }
        $custom['CUSTOM_NUT'][] = $d['raw'];
    }
    $custom['CUSTOM_UPSSCHED'] = array_column($parse('upssched.conf'), 'raw');

    if (!$slave && $c['IPADDR'] !== '127.0.0.1') {
        if (!in_array(explode(':', $c['IPADDR'])[0], ['127.0.0.1', 'localhost'], true)) {
            $notes[] = "The local NUT monitor now connects to 127.0.0.1 instead of {$c['IPADDR']}.";
        }
        $c['IPADDR'] = '127.0.0.1';
    }
    foreach ($custom as $key => $lines) {
        $c[$key] = $lines ? base64_encode(implode("\n", $lines) . "\n") : '';
        if ($lines) $notes[] = NUT_MC_CUSTOM[$key][1] . ': ' . count($lines) . ' line(s) were kept as custom directives.';
    }
    return [$c, $notes];
}

/* Apply the first device found by nut-scanner (ups.conf syntax) to the UPS driver settings. */
function nut_mc_apply_scan(array $cfg, $text) {
    $c = nut_mc_settings($cfg);
    $entries = nut_mc_parse($text);
    $sections = array_values(array_unique(array_column(array_filter($entries, fn($d) => $d['header']), 'section')));
    if (!$sections) return [$cfg, ['No UPS device was found in the scan results, no settings were changed.']];
    $pick = $sections[0];
    $found = [];
    $taken = [];
    $custom = [];
    $snmp = nut_mc_section_driver($entries, $pick) === 'snmp-ups';
    foreach ($entries as $d) {
        if ($d['section'] === $pick && !$d['header'] && !nut_mc_ups_directive($d, $found, $taken, $snmp)) $custom[] = $d['raw'];
    }
    $msgs = [];
    foreach ($found as $key => $value) {
        if (preg_match(NUT_MC_UNSAFE, $value)) {
            $msgs[] = "The detected value for $key contains unsupported characters and was not applied.";
        } else {
            $c[$key] = $value;
        }
    }
    $c['CUSTOM_UPS'] = $custom ? base64_encode(implode("\n", $custom) . "\n") : '';
    $msgs[] = "Applied device [$pick]: driver " . ($c['DRIVER'] === 'custom' ? $c['SERIAL'] : $c['DRIVER']) . ", port {$c['PORT']}.";
    $msgs[] = $custom ? 'The other detected details replaced the ups.conf (UPS section) custom directives.' : 'The ups.conf (UPS section) custom directives were cleared.';
    if (count($sections) > 1) $msgs[] = 'Other detected devices were ignored: [' . implode('], [', array_slice($sections, 1)) . '].';
    return [$c, $msgs];
}

/* The import report exists from the import until the first generation; "accepted" marks the user's save. */
function nut_mc_report($dir = NUT_MC_DIR) {
    $report = is_file("$dir/import-report.json") ? json_decode((string)file_get_contents("$dir/import-report.json"), true) : null;
    return is_array($report) ? $report : null;
}

function nut_mc_pending($dir = NUT_MC_DIR) {
    $report = nut_mc_report($dir);
    return $report && empty($report['accepted']) ? $report : null;
}

function nut_mc_accept($dir = NUT_MC_DIR) {
    $report = nut_mc_pending($dir);
    return !$report || nut_mc_put("$dir/import-report.json", json_encode(['accepted' => true] + $report, JSON_PRETTY_PRINT) . "\n");
}

/* True if the flash drive holds NUT files that this generator did not write. */
function nut_mc_is_legacy($dir = NUT_MC_DIR) {
    foreach (NUT_MC_FILES as $name) {
        $path = "$dir/ups/$name";
        if (is_file($path) && strncmp((string)file_get_contents($path), NUT_MC_MARK, strlen(NUT_MC_MARK)) !== 0) return true;
    }
    return false;
}

function nut_mc_import_dir($dir = NUT_MC_DIR) {
    $cfgPath = "$dir/nut3.cfg";
    $files = [];
    @mkdir("$dir/backup/legacy", 0700, true);
    foreach (NUT_MC_FILES as $name) {
        $files[$name] = is_file("$dir/ups/$name") ? file_get_contents("$dir/ups/$name") : null;
        if ($files[$name] !== null && !is_file("$dir/backup/legacy/$name")) copy("$dir/ups/$name", "$dir/backup/legacy/$name");
    }
    if (is_file($cfgPath) && !is_file("$dir/backup/legacy/nut3.cfg")) copy($cfgPath, "$dir/backup/legacy/nut3.cfg");
    [$cfg, $notes] = nut_mc_import(nut_mc_read_cfg($cfgPath), $files);
    return nut_mc_write_cfg($cfgPath, $cfg)
        && nut_mc_put("$dir/import-report.json", json_encode(['date' => date('Y-m-d H:i'), 'notes' => $notes], JSON_PRETTY_PRINT) . "\n");
}

/*
 * Write the generated files to $dir/ups (the source rc.nut copies to /etc/nut). A previous configuration
 * is imported first and keeps being used until the user saves the imported settings (import pending).
 * Returns false with $messages listing the problems if the settings are invalid; nothing is written then.
 */
function nut_mc_deploy($dir, &$messages) {
    $messages = [];
    $report = nut_mc_report($dir);
    if (!$report && nut_mc_is_legacy($dir)) {
        if (!nut_mc_import_dir($dir)) {
            $messages[] = 'Importing the previous NUT configuration failed.';
            return false;
        }
        $messages[] = 'The previous NUT configuration was imported into the settings, review and apply it on the NUT Settings page.';
    }
    if (nut_mc_pending($dir)) {
        $messages[] = 'Imported settings are awaiting review, the previous NUT configuration files stay in use until they are applied.';
        return true;
    }
    $cfg = nut_mc_settings(nut_mc_read_cfg("$dir/nut3.cfg"));
    if ($messages = nut_mc_validate($cfg)) return false;
    @mkdir("$dir/ups", 0700, true);
    @mkdir("$dir/backup", 0700, true);
    foreach (nut_mc_generate($cfg) as $name => $text) {
        $path = "$dir/ups/$name";
        $old = is_file($path) ? file_get_contents($path) : null;
        if ($old === $text) continue;
        if ($old !== null) copy($path, "$dir/backup/$name.bak");
        if (!nut_mc_put($path, $text)) {
            $messages[] = "Writing $path failed.";
            return false;
        }
    }
    if ($report) @unlink("$dir/import-report.json");
    return true;
}
