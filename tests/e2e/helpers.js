// @ts-check
// Shared fixtures for the page tests. The Unraid root that harness.py serves belongs to root, so files in it
// are read and written through sudo (passwordless on the CI runner).
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { test: base, expect } = require('@playwright/test');

const WORK = process.env.E2E_WORK || '/tmp/nut-e2e';
const ROOT = path.join(WORK, 'root');
const REPO = path.resolve(__dirname, '../..');
const FLASH = '/boot/config/plugins/nut-dw';
const FIXTURES = '/var/tmp/nut-e2e';
const SETTINGS = '/Settings/NUTsettings';
const NUT_FILES = ['nut.conf', 'ups.conf', 'upsd.conf', 'upsd.users', 'upsmon.conf', 'upssched.conf'];
const MARK = '# Generated by the NUT plugin (nut-dw)';
// the NUT backend the .plg installs on Unraid 7.3.4 and later
const BACKEND = /<!ENTITY nutNAME\s+"([^"]+)">/.exec(fs.readFileSync(path.join(REPO, 'plugin/nut-dw.plg'), 'utf8'))[1];

function sudo(args, input) {
  return execFileSync('sudo', ['-n', ...args], { input, encoding: 'utf8', stdio: ['pipe', 'pipe', 'inherit'] });
}

/** Files and commands inside the served Unraid root (paths as the server sees them). */
const root = {
  read: (file) => sudo(['cat', ROOT + file]),
  exists: (file) => {
    try {
      sudo(['test', '-e', ROOT + file]);
      return true;
    } catch {
      return false;
    }
  },
  write: (file, text) => void sudo(['tee', ROOT + file], text),
  sh: (script) => sudo(['chroot', ROOT, '/bin/bash', '-c', script]),
};

const b64 = (text) => Buffer.from(text).toString('base64');

/** Change settings in nut-dw.cfg the way /update.php stores them. */
function setCfg(values) {
  let text = root.read(`${FLASH}/nut-dw.cfg`);
  for (const [key, value] of Object.entries(values)) {
    const line = `${key}="${value}"`;
    const pattern = new RegExp(`^${key}=.*$`, 'm');
    text = pattern.test(text) ? text.replace(pattern, line) : `${text}${line}\n`;
  }
  root.write(`${FLASH}/nut-dw.cfg`, text);
}

/** Checksums of everything in the plugin's flash directory, to prove that nothing was written. */
const flashChecksums = () =>
  sudo(['bash', '-c', 'cd "$1" && find . -type f -print0 | sort -z | xargs -0 sha256sum', '-', ROOT + FLASH]);

/** The generated NUT files on the flash drive. */
const upsFiles = () => Object.fromEntries(NUT_FILES.map((name) => [name, root.read(`${FLASH}/ups/${name}`)]));

/** Start the upsmon stand-in, so the pages see NUT running. */
const startUpsmon = () => root.sh('/usr/sbin/upsmon -p && for i in $(seq 50); do pgrep -x upsmon >/dev/null && exit; sleep 0.1; done; exit 1');

/** Wait until the page's jQuery requests are done. */
const settled = (page) => page.waitForFunction(() => window.jQuery && window.jQuery.active === 0);

/** Apply the NUT settings form and wait for /update.php to finish, after which Unraid reloads the page. */
async function apply(page) {
  const reloaded = page.waitForEvent('load', { timeout: 90_000 });
  await page.locator('#btnApply').click();
  await reloaded;
  await expect(page.locator('#nut-settings')).toBeVisible();
}

/** Apply settings the page's own check rejects; the error dialog appears and the page stays. */
async function applyRejected(page, ...errors) {
  await page.locator('#btnApply').click();
  const dialog = page.locator('.sweet-alert');
  await expect(dialog).toBeVisible();
  await expect(dialog.locator('h2')).toHaveText('Settings not applied');
  for (const error of errors) await expect(dialog).toContainText(error);
  await dialog.locator('button.confirm').click();
  await expect(dialog).toBeHidden();
}

const test = base.extend({
  // Every test starts from the freshly installed plugin and fails on JavaScript errors.
  page: async ({ page }, use, testInfo) => {
    sudo(['python3', path.join(__dirname, 'harness.py'), '--work', WORK, 'reset']);
    const problems = [];
    const ignored = (description) => testInfo.annotations.push({ type: 'environment', description });
    page.on('pageerror', (error) => problems.push(`page error: ${error.stack || error.message}`));
    page.on('console', (message) => {
      if (message.type() !== 'error') return;
      const text = `${message.text()} (${message.location().url})`;
      // no emhttpd or Unraid API runs here: failed loads outside the plugin are gaps of the test server
      if ((/^Failed to load resource/.test(message.text()) && !message.location().url.includes('/plugins/nut-dw/'))
        || /WebSocket connection to .*\/sub\//.test(message.text())) {
        ignored(text);
      } else {
        problems.push(`console error: ${text}`);
      }
    });
    page.on('response', (response) => {
      if (response.status() < 400) return;
      const text = `HTTP ${response.status()} ${response.url()}`;
      if (response.url().includes('/plugins/nut-dw/')) problems.push(text);
      else ignored(text);
    });
    await use(page);
    expect(problems, 'JavaScript errors and failed plugin requests').toEqual([]);
  },
});

module.exports = {
  test, expect, root, b64, setCfg, flashChecksums, upsFiles, startUpsmon, settled, apply, applyRejected,
  REPO, FLASH, FIXTURES, SETTINGS, NUT_FILES, MARK, BACKEND,
};
